    public void llenarCabecera() {
        ArrayList<Object> c = new ArrayList<>();
        c.add("idPasaje");
        c.add("DNI");
        c.add("Nombre");
        c.add("Origen");
        c.add("Destino");

        tblPasaje.setModel(modelo);
        for (Object it : c) {
            modelo.addColumn(it);
        }
    }

    private void cargarTabla(String filtro) {
        modelo.setRowCount(0);
        for (Pasaje p : pd.buscarPasajesActivos(filtro)) {
            modelo.addRow(new Object[]{
                p.getIdPasaje(),
                p.getPasajero().getDni(),
                p.getPasajero().getNombre() + " " + p.getPasajero().getApellido(),
                p.getRutaViaje().getOrigen(),
                p.getRutaViaje().getDestino()
            });
        }
    }

    private void configurarBuscador() {
        tblPasaje.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        txtFiltrar.getDocument().addDocumentListener(new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) {
                cargarTabla(txtFiltrar.getText());
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                cargarTabla(txtFiltrar.getText());
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
                cargarTabla(txtFiltrar.getText());
            }
        });
    }
