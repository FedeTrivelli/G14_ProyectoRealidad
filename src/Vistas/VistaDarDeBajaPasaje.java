    private void btnDarBajaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDarBajaActionPerformed
        // TODO add your handling code here:
        int fila = tblPasaje.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccioná un pasaje de la tabla.",
                    "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int idPasaje = (int) modelo.getValueAt(fila, 0);
        String pasajero = (String) modelo.getValueAt(fila, 2);

        int opcion = JOptionPane.showConfirmDialog(this,
                "¿Dar de baja el pasaje " + idPasaje + " de " + pasajero + "?",
                "Confirmar baja", JOptionPane.YES_NO_OPTION);

        if (opcion == JOptionPane.YES_OPTION) {
            if (pd.darDeBaja(idPasaje)) {
                JOptionPane.showMessageDialog(this, "Pasaje dado de baja correctamente.");
                cargarTabla(txtFiltrar.getText());
            }
        }

    }//GEN-LAST:event_btnDarBajaActionPerformed


