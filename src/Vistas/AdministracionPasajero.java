    public void llenarCabecera() {
        ArrayList<Object> c = new ArrayList<>();
        c.add("id");
        c.add("Dni");
        c.add("Nombre");
        c.add("Apellido");
        c.add("Correo");
        c.add("Telefono");
        c.add("Estado");

        tblPasajeros.setModel(modelo);
        for (Object it : c) {
            modelo.addColumn(it);
        }
    }

    private void cargarTabla() {
        modelo.setRowCount(0);
        pasajeros = pd.listarPasajeros();
        for (Pasajero r : pasajeros) {
            modelo.addRow(new Object[]{
                r.getIdPasajero(), r.getDni(), r.getNombre(),
                r.getApellido(), r.getCorreo(), r.getTelefono(), r.isEstado()
            });
        }
    }

    private void configurarBusqueda() {
        sorter = new TableRowSorter<>(modelo);
//        tblPasajeros.setRowSorter(sorter);

        txtBuscar.getDocument().addDocumentListener(new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) {
                filtrar();
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                filtrar();
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
                filtrar();
            }
        });
    }

    private void filtrar() {
        String texto = txtBuscar.getText().trim();
        if (texto.isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            sorter.setRowFilter(RowFilter.regexFilter("(?i)" + Pattern.quote(texto)));
        }
    }

