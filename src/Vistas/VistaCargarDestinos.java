    private LocalDate obtenerFecha(JDateChooser fecha) {
        if (fecha == null || fecha.getDate() == null) {
            return null;
        }
        return fecha.getDate().toInstant().atZone(ZoneId.systemDefault()).toLocalDate();
    }

    private LocalTime obtenerHora(JSpinner hora) {
        if (hora == null || hora.getValue() == null) {
            return null;
        }
        return ((Date) hora.getValue()).toInstant()
                .atZone(ZoneId.systemDefault()).toLocalTime()
                .withSecond(0).withNano(0);
    }

    private void mostrarFecha(LocalDate fecha, JDateChooser fechaChooser) {
        if (fecha == null) {
            fechaChooser.setDate(null);
            return;
        }
        fechaChooser.setDate(Date.from(fecha.atStartOfDay(ZoneId.systemDefault()).toInstant()));
    }

    private void mostrarHora(LocalTime hora, JSpinner horaSpinner) {
        if (hora == null) {
            horaSpinner.setValue(new Date());
            return;
        }
        Date d = Date.from(hora.atDate(LocalDate.of(2000, 1, 1)).atZone(ZoneId.systemDefault()).toInstant());
        horaSpinner.setValue(d);
    }

    public void cargarRuta(RutaViaje ruta) {
        rv = ruta;
        txtCargarOrigen.setText(ruta.getOrigen());
        txtCargarDestino.setText(ruta.getDestino());
        mostrarFecha(ruta.getFechaSalida(), dtcCargarPartida);
        mostrarHora(ruta.getHoraSalida(), spnHoraSalida);
        mostrarHora(ruta.getHoraLlegada(), spnHoraRegreso);
        cmbColectivo.setSelectedItem(ruta.getColectivo());
        txtPrecio.setText(String.valueOf(ruta.getPrecio()));
        ckbEstado.setSelected(ruta.isEstado());
        activarBotones();
    }

    private boolean volcarFormularioEn(RutaViaje ruta) {
        String origen = txtCargarOrigen.getText().trim();
        String destino = txtCargarDestino.getText().trim();

        if (origen.isEmpty() || destino.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Completá el origen y el destino.");
            return false;
        }

        if (origen.equalsIgnoreCase(destino)) {
            JOptionPane.showMessageDialog(this, "El origen y el destino no pueden ser iguales.");
            return false;
        }

        if (cmbColectivo.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Seleccioná un colectivo.");
            return false;
        }

        LocalDate fechaPartida = obtenerFecha(dtcCargarPartida);
        if (fechaPartida == null) {
            JOptionPane.showMessageDialog(this, "Seleccioná la fecha de partida.");
            return false;
        }

        int precio;
        try {
            precio = Integer.parseInt(txtPrecio.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El precio debe ser un número entero.");
            return false;
        }
        if (precio <= 0) {
            JOptionPane.showMessageDialog(this, "El precio debe ser mayor a cero.");
            return false;
        }

        LocalTime salida = obtenerHora(spnHoraSalida);
        LocalTime llegada = obtenerHora(spnHoraRegreso);
        if (salida == null || llegada == null) {
            JOptionPane.showMessageDialog(this, "Seleccioná las horas de salida y llegada.");
            return false;
        }

        ruta.setOrigen(origen);
        ruta.setDestino(destino);
        ruta.setFechaSalida(fechaPartida);
        ruta.setHoraSalida(salida);
        ruta.setHoraLlegada(llegada);
        ruta.setColectivo((Colectivo) cmbColectivo.getSelectedItem());
        ruta.setPrecio(precio);
        ruta.setEstado(ckbEstado.isSelected());
        return true;
    }

    public void guardarRuta() {
        if (dtcCargarPartida.getDate() != null
                && obtenerFecha(dtcCargarPartida).isBefore(LocalDate.now())) {
            JOptionPane.showMessageDialog(this, "La fecha de partida no puede ser anterior a hoy.");
            return;
        }

        RutaViaje nueva = new RutaViaje();
        if (!volcarFormularioEn(nueva)) {
            return;
        }
        rd.guardarRuta(nueva);
        inicio();
    }

    public void borrarRuta(int idRuta) {
        if (rd.buscarRuta(idRuta) == null) {
            JOptionPane.showMessageDialog(this, "No se pudo borrar la ruta.\nRazón:\nEl ID de la ruta ingresada no existe.");
            return;
        }

        int respuesta = JOptionPane.showConfirmDialog(this, "¿Realmente desea eliminar la ruta?",
                "Borrado de Ruta", JOptionPane.YES_NO_OPTION);

        if (respuesta == JOptionPane.YES_OPTION) {
            rd.borrarRuta(idRuta);
            inicio();
        }
    }

    public void actualizarRuta() {
        if (rv == null || rv.getIdRuta() <= 0) {
            JOptionPane.showMessageDialog(this, "Primero tenés que cargar una ruta existente para actualizarla.");
            return;
        }
        if (!volcarFormularioEn(rv)) {
            return;
        }
        rd.actualizarRuta(rv);
    }

    private void llenarCmb() {
        cmbColectivo.removeAllItems();
        for (Colectivo c : cd.listarColectivo()) {
            cmbColectivo.addItem(c);
        }
        cmbColectivo.setSelectedIndex(-1);
    }

    public void llenarCabecera() {
        ArrayList<Object> c = new ArrayList<>();
        c.add("id");
        c.add("Origen");
        c.add("Destino");
        c.add("Colectivo");
        c.add("Fecha");
        c.add("Hora salida");
        c.add("Hora llegada");
        c.add("Precio");
        c.add("Estado");

        for (Object it : c) {
            modelo.addColumn(it);
            TblDestinos.setModel(modelo);
        }
    }

    private void cargarTabla() {
        modelo.setRowCount(0);
        listaRutas = rd.listarRutas();
        for (RutaViaje r : listaRutas) {
            modelo.addRow(new Object[]{
                r.getIdRuta(),
                r.getOrigen(),
                r.getDestino(),
                r.getColectivo(),
                r.getFechaSalida().format(DateTimeFormatter.ofPattern("dd/MM/yyyy")),
                r.getHoraSalida().format(DateTimeFormatter.ofPattern("HH:mm")),
                r.getHoraLlegada().format(DateTimeFormatter.ofPattern("HH:mm")),
                r.getPrecio(),
                r.isEstado() ? "Activo" : "Inactivo"
            });
        }
    }

    private void SeleccionTabla() {
        TblDestinos.getSelectionModel().addListSelectionListener(e -> {
            int fila = TblDestinos.getSelectedRow();
            if (!e.getValueIsAdjusting() && fila >= 0) {
                cargarRuta(listaRutas.get(fila));
            }
        });
    }
