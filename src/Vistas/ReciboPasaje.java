    public void cargarDatos(Pasaje p) {
        DateTimeFormatter fecha = DateTimeFormatter.ofPattern("dd/MM/yyyy");
        DateTimeFormatter hora = DateTimeFormatter.ofPattern("HH:mm");

        if (p.getRutaViaje() != null) {
            lblOrigen.setText(p.getRutaViaje().getOrigen());
            lblDestino.setText(p.getRutaViaje().getDestino());

            if (p.getRutaViaje().getFechaSalida() != null
                    && p.getRutaViaje().getHoraSalida() != null) {
                lblSalida.setText(p.getRutaViaje().getFechaSalida().format(fecha)
                        + " " + p.getRutaViaje().getHoraSalida().format(hora));
            }
            if (p.getRutaViaje().getFechaSalida() != null
                    && p.getRutaViaje().getHoraLlegada() != null) {
                lblLlegada.setText(p.getRutaViaje().getFechaSalida().format(fecha)
                        + " " + p.getRutaViaje().getHoraLlegada().format(hora));
            }
            if (p.getRutaViaje().getColectivo() != null) {
                lblChofer.setText(p.getRutaViaje().getColectivo().getChofer());
                lblMatricula.setText(p.getRutaViaje().getColectivo().getMatricula());
            }
        }

        if (p.getPasajero() != null) {
            lblPasajero.setText(p.getPasajero().getApellido() + ", "
                    + p.getPasajero().getNombre());
            lblDni.setText(String.valueOf(p.getPasajero().getDni()));
        }
        if (p.getLugar() != null) {
            lblAsiento.setText(String.valueOf(p.getLugar().getNumeroAsiento()));
        }
        lblPrecio.setText("$" + p.getPrecio());

        if (p.getPasajeFecha() != null && p.getPasajeHora() != null) {
            lblFechaVenta.setText(p.getPasajeFecha().format(fecha)
                    + " " + p.getPasajeHora().format(hora));
        }
    }
